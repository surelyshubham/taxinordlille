import type { Metadata } from "next";
import { notFound } from "next/navigation";

import { PageHero } from "@/components/site/page-hero";
import { Photo } from "@/components/site/photo";
import credits from "@/lib/photos/credits.json";
import { PHOTOS, isPhotoName, type PhotoName } from "@/lib/photos";
import { isLocale, localizedHref } from "@/lib/i18n/config";

/**
 * Photo credits.
 *
 * This page exists because of the licences, not for decoration. Every
 * photograph is public-domain or Creative Commons, and CC BY / CC BY-SA both
 * require attribution: author, licence, a link to the licence, a link to the
 * source, and — because the images are cropped and tone-mapped here — a note
 * saying so. That is the whole of the obligation; it is also the page a
 * visitor or a Commons editor would expect to find.
 *
 * The data is generated by `scripts/process-photos.mjs` into
 * `src/lib/photos/credits.json`, so it cannot drift from the files that
 * actually ship.
 */

type Copy = {
  title: string;
  intro: string;
  adaptationsLabel: string;
  adaptations: string;
  licenceLabel: string;
  sourceLabel: string;
  authorLabel: string;
};

const COPY: Record<string, Copy> = {
  fr: {
    title: "Crédits photographiques",
    intro:
      "Les photographies de ce site proviennent de Wikimedia Commons et sont diffusées sous licence libre. Elles ont été recadrées et étalonnées dans les tons de la marque. Cette page indique l'auteur, la licence et la source de chacune.",
    adaptationsLabel: "Modifications apportées",
    adaptations: credits.adaptations,
    licenceLabel: "Licence",
    sourceLabel: "Source",
    authorLabel: "Auteur",
  },
  en: {
    title: "Photo credits",
    intro:
      "The photographs on this site come from Wikimedia Commons and are published under free licences. They have been cropped and tone-mapped into the brand's palette. This page states the author, licence and source of each one.",
    adaptationsLabel: "Changes made",
    adaptations: credits.adaptationsEn,
    licenceLabel: "Licence",
    sourceLabel: "Source",
    authorLabel: "Author",
  },
};

export async function generateMetadata({
  params,
}: {
  params: Promise<{ lang: string }>;
}): Promise<Metadata> {
  const { lang } = await params;
  if (!isLocale(lang)) notFound();
  const copy = COPY[lang];

  return {
    title: copy.title,
    description: copy.intro,
    // Attribution is required for these images wherever they are reachable,
    // including from search results, so this page stays indexable.
    robots: { index: true, follow: true },
    alternates: {
      canonical: localizedHref(lang, "/credits-photographiques"),
      languages: {
        fr: localizedHref("fr", "/credits-photographiques"),
        en: localizedHref("en", "/credits-photographiques"),
      },
    },
  };
}

export default async function PhotoCreditsPage({
  params,
}: {
  params: Promise<{ lang: string }>;
}) {
  const { lang } = await params;
  if (!isLocale(lang)) notFound();
  const copy = COPY[lang];
  type CreditedPhoto = (typeof credits.photos)[number] & { slug: PhotoName };
  const photos = credits.photos.filter(
    (photo): photo is CreditedPhoto => isPhotoName(photo.slug),
  );

  return (
    <>
      <PageHero
        title={copy.title}
        intro={copy.intro}
        homeLabel={
          lang === "fr" ? "Accueil" : "Home"
        }
        breadcrumbs={[
          { name: copy.title, href: localizedHref(lang, "/credits-photographiques") },
        ]}
      />

      <section className="pb-24">
        <div className="mx-auto max-w-7xl px-5 sm:px-8">
          <p className="max-w-3xl border-l-2 border-gold-600/50 pl-5 text-sm leading-relaxed text-content-muted">
            <span className="font-semibold text-gold-300">
              {copy.adaptationsLabel} :
            </span>{" "}
            {copy.adaptations}
          </p>

          <ul className="mt-12 grid gap-6 sm:grid-cols-2 lg:grid-cols-3">
            {photos.map((photo) => (
              <li
                key={photo.slug}
                className="surface-card edge-top flex flex-col overflow-hidden rounded-2xl"
              >
                <div className="relative aspect-video overflow-hidden border-b border-line">
                  <Photo
                    name={photo.slug}
                    locale={lang}
                    sizes="(min-width: 1024px) 380px, (min-width: 640px) 45vw, 92vw"
                    width={640}
                    height={360}
                  />
                </div>

                <div className="flex flex-1 flex-col p-6">
                  <p className="text-sm font-semibold text-content">
                    {PHOTOS[photo.slug].place[lang]}
                  </p>

                  <dl className="mt-4 space-y-2 text-sm">
                    <div className="flex gap-2">
                      <dt className="shrink-0 text-content-subtle">
                        {copy.authorLabel} :
                      </dt>
                      <dd className="text-content-muted">{photo.author}</dd>
                    </div>
                    <div className="flex gap-2">
                      <dt className="shrink-0 text-content-subtle">
                        {copy.licenceLabel} :
                      </dt>
                      <dd>
                        <a
                          href={photo.licenceUrl}
                          target="_blank"
                          rel="noopener noreferrer license"
                          className="text-gold-300 underline decoration-gold-600 underline-offset-4 transition-colors hover:text-gold-200"
                        >
                          {photo.licence}
                        </a>
                      </dd>
                    </div>
                    <div className="flex gap-2">
                      <dt className="shrink-0 text-content-subtle">
                        {copy.sourceLabel} :
                      </dt>
                      <dd>
                        <a
                          href={photo.source}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="break-all text-gold-300 underline decoration-gold-600 underline-offset-4 transition-colors hover:text-gold-200"
                        >
                          Wikimedia Commons
                        </a>
                      </dd>
                    </div>
                  </dl>
                </div>
              </li>
            ))}
          </ul>
        </div>
      </section>
    </>
  );
}
